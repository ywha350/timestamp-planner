import { test, expect } from '@playwright/test';
test.beforeEach(async ({page}, info) => {
  if (info.title.startsWith('initial start')) return;
  await page.goto('/');
  await page.locator('.start').click();
  await page.keyboard.press('Enter');
  await expect(page.locator('.time').first()).toBeFocused();
});
test('initial start accepts a custom time before the first end time', async ({page}) => {
  await page.goto('/');
  const start = page.locator('.start');
  await start.click(); await page.keyboard.insertText('093');
  await page.reload(); await expect(start).toHaveValue('093');
  await start.click(); await page.keyboard.insertText('0');
  const time = page.locator('.time').first();
  await expect(time).toHaveValue('09:30-09:30');
  await expect(time).toBeFocused();
  await page.keyboard.press('Space');
  await expect(time).toHaveValue('09:30-09:40');
  await page.keyboard.press('Enter'); await page.keyboard.insertText('study');
  await page.keyboard.press('Enter');
  await expect(page.locator('.time').nth(1)).toHaveValue('09:40-09:40');
  await page.reload(); await expect(start).toHaveCount(0);
  await expect(time).toHaveValue('09:30-09:40');
});
