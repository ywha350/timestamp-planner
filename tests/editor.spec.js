test('clear all cancels safely or resets the stored plan', async ({page}) => {
  await page.goto('/');
  await page.locator('.time').first().click();
  await page.keyboard.press('Space'); await page.keyboard.press('Enter');
  await page.keyboard.insertText('study');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', {name:'전체 삭제'}).click();
  await expect(page.locator('.task')).toHaveValue('study');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', {name:'전체 삭제'}).click();
  await expect(page.locator('.start')).toBeFocused();
  await expect(page.locator('.start')).toHaveValue('');
  await expect(page.locator('.task')).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => new Promise(resolve => {
    const request = indexedDB.open('plain-day-planner', 1);
    request.onsuccess = () => {
      const db = request.result;
      const get = db.transaction('plans').objectStore('plans').get('document');
      get.onsuccess = () => { resolve(get.result); db.close(); };
    };
  }))).toEqual([{start:0,minutes:0,task:'',startPending:true,startDraft:''}]);
  await page.reload();
  await expect(page.locator('.start')).toHaveValue('');
  await page.locator('.start').click(); await page.keyboard.insertText('1030');
  await expect(page.locator('.time')).toHaveValue('10:30-10:30');
});
test('copy all exports lines and actions align on one row', async ({page, context}) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.setViewportSize({width:320,height:640});
  await page.goto('/');
  await page.locator('.time').first().click();
  await page.keyboard.press('Space'); await page.keyboard.press('Enter');
  await page.keyboard.insertText('study'); await page.keyboard.press('Enter');
  await page.keyboard.press('Space'); await page.keyboard.press('Enter');
  await page.keyboard.insertText('break');
  const copy = page.getByRole('button', {name:'전체 복사'});
  const clear = page.getByRole('button', {name:'전체 삭제'});
  const left = await copy.boundingBox(); const right = await clear.boundingBox();
  expect(left.y).toBe(right.y);
  expect(left.x).toBe(12);
  expect(right.x + right.width).toBe(308);
  await copy.click();
  await expect.poll(() => page.evaluate(async () => (await navigator.clipboard.readText()).replace(/\r\n/g, '\n'))).toBe('00:00-00:10 (10m) study\n00:10-00:20 (10m) break');
  await expect(page.locator('.task').first()).toHaveValue('study');
});
test('shortcuts, selection, persistence and offline', async ({page, context}) => {
  await page.goto('/');
  const times = page.locator('.time'); const tasks = page.locator('.task');
  await times.first().click();
  await page.keyboard.press('Space'); await page.keyboard.press('Space');
  await expect(times.first()).toHaveValue('00:00-00:20');
  await page.keyboard.press('Backspace');
  await expect(times.first()).toHaveValue('00:00-00:10');
  await page.keyboard.press('Enter'); await page.keyboard.insertText('\uC218\uD559 \uACF5\uBD80');
  await page.keyboard.press('Enter');
  await expect(times.nth(1)).toHaveValue('00:10-00:10');
  await page.keyboard.press('Backspace');
  await expect(tasks.first()).toHaveValue('\uC218\uD559 \uACF5\uBD80');
  await expect(page.locator('.row')).toHaveCount(1);
  await page.keyboard.press('Backspace'); await expect(tasks.first()).toHaveValue('');
  await page.keyboard.press('Backspace'); await expect(times.first()).toHaveValue('00:00-00:10');
  await expect.poll(() => times.first().evaluate(el => el.value.slice(el.selectionStart, el.selectionEnd))).toBe('00:10');
  await expect.poll(() => times.first().evaluate(el => [el.selectionStart, el.selectionEnd])).toEqual([6, 11]);
  await page.keyboard.press('Backspace'); await expect(times.first()).toHaveValue('00:00-00:00');
  await page.keyboard.press('Space'); await page.keyboard.press('Enter');
  await page.keyboard.insertText('\uC601\uC5B4');
  await expect.poll(() => page.evaluate(async () => {
    return new Promise(resolve => {
      const request = indexedDB.open('plain-day-planner', 1);
      request.onsuccess = () => {
        const db = request.result;
        const get = db.transaction('plans').objectStore('plans').get('document');
        get.onsuccess = () => { resolve(get.result[0].task); db.close(); };
      };
    });
  })).toBe('\uC601\uC5B4');
  await page.reload(); await expect(tasks.first()).toHaveValue('\uC601\uC5B4');
  await expect(page.locator('.row')).toHaveCount(1);
  await page.evaluate(() => navigator.serviceWorker.ready);
  await context.setOffline(true); await page.reload();
  await expect(tasks.first()).toHaveValue('\uC601\uC5B4');
});
