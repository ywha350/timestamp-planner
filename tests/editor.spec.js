test('anywhere tap resumes input and cursor movement is locked', async ({page}) => {
  await page.goto('/');
  await expect(page.locator('.time').first()).toBeVisible();
  await page.mouse.click(250, 400);
  await expect(page.locator('.time').first()).toBeFocused();
  await page.keyboard.press('Space'); await page.keyboard.press('Enter');
  await page.keyboard.insertText('study');
  await page.keyboard.press('ArrowLeft'); await page.keyboard.press('Home');
  await page.keyboard.insertText('!');
  const task = page.locator('.task').first();
  await expect(task).toHaveValue('study!');
  await page.locator('.time').first().click();
  await expect(task).toBeFocused();
  await page.keyboard.press('Tab'); await expect(task).toBeFocused();
  await task.evaluate(el => el.setSelectionRange(0, 2));
  await expect.poll(() => task.evaluate(el => [el.selectionStart, el.selectionEnd])).toEqual([6, 6]);
  await page.keyboard.press('Enter'); await page.keyboard.press('Backspace');
  await page.mouse.click(250, 400);
  await page.keyboard.press('Backspace'); await expect(task).toHaveValue('');
  expect(await page.evaluate(() => !document.dispatchEvent(new WheelEvent('wheel', {ctrlKey:true,cancelable:true})))).toBe(true);
  expect(await page.evaluate(() => !document.dispatchEvent(new KeyboardEvent('keydown', {ctrlKey:true,key:'+',cancelable:true})))).toBe(true);
});
